/** A picture for the crop buttons (emoji, so no image files are needed). */
fun cropEmoji(crop: String): String {
    val k = crop.lowercase()
    return when {
        k.startsWith("tomato") -> "🍅"; k.startsWith("potato") -> "🥔"; k.startsWith("corn") -> "🌽"
        k.startsWith("pepper") -> "🫑"; k.startsWith("grape") -> "🍇"; k.startsWith("apple") -> "🍎"
        k.startsWith("cherry") -> "🍒"; k.startsWith("peach") -> "🍑"; k.startsWith("strawberry") -> "🍓"
        k.startsWith("orange") -> "🍊"; k.startsWith("squash") -> "🎃"; k.startsWith("blueberry") -> "🫐"
        else -> "🌿"
    }
}


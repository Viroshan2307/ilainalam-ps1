    TE("te", "తెలుగు", Locale("te", "IN")),
    KN("kn", "ಕನ್ನಡ", Locale("kn", "IN"));

    companion object {
        fun fromCode(c: String?) = entries.firstOrNull { it.code == c } ?: EN
    }

/** Indian cropping season from the phone's month: Kharif Jun–Oct, Rabi Nov–Mar, Zaid Apr–May. */
enum class Season(val en: String, val hi: String, val ta: String, val ml: String, val te: String, val kn: String) {
    KHARIF("Kharif (monsoon)", "ख़रीफ़", "காரீஃப்", "ഖരീഫ് (മഴക്കാലം)", "ఖరీఫ్", "ಮುಂಗಾರು (ಖಾರಿಫ್)"),
    RABI("Rabi (winter)", "रबी", "ராபி", "റാബി (മഞ്ഞുകാലം)", "రబీ", "ಹಿಂಗಾರು (ರಬಿ)"),
    ZAID("Zaid (summer)", "ज़ायद", "சைத்", "സായിദ് (വേനൽ)", "జాయిద్ (వేసవి)", "ಬೇಸಿಗೆ (ಜಾಯಿದ್)");
    fun display(lang: Lang) = when (lang) { Lang.HI -> hi; Lang.TA -> ta; Lang.ML -> ml; Lang.TE -> te; Lang.KN -> kn; Lang.EN -> en }
    companion object {
        /** [month] is 1–12. */
        fun of(month: Int): Season = when (month) { in 6..10 -> KHARIF; 4, 5 -> ZAID; else -> RABI }
    }
}
